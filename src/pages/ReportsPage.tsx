// ── Helper: download a blob as a file ─────────────────────────────────────
function downloadBlob(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function downloadReport(item: ReportHistoryItem) {
  const isPdf = item.format === 'PDF';
  const filename = `${item.reportName.replace(/\s+/g, '_')}.${isPdf ? 'pdf' : 'csv'}`;
  const content = isPdf
    ? `Mock PDF Report: ${item.reportName}\nType: ${item.reportType}\nSite: ${item.site}\nChainage: ${item.chainage}\nGenerated By: ${item.generatedBy}\nDate: ${item.generatedDate}`
    : `Report Name,Report Type,Site,Chainage,Generated By,Date\n${item.reportName},${item.reportType},${item.site},${item.chainage},${item.generatedBy},${item.generatedDate}`;
  const mimeType = isPdf ? 'application/pdf' : 'text/csv';
  downloadBlob(content, filename, mimeType);
}

// ── Status badge helper ───────────────────────────────────────────────────
function StatusBadge({ status }: { status: ReportHistoryItem['status'] }) {
  const map: Record<string, { bg: string; icon: string }> = {
    Ready: { bg: 'text-bg-success', icon: '🟢' },
    Generating: { bg: 'text-bg-warning', icon: '🟡' },
    Failed: { bg: 'text-bg-danger', icon: '🔴' },
  };
  const c = map[status] ?? { bg: 'text-bg-secondary', icon: '⚪' };
  return (
    <span className={`badge ${c.bg}`}>
      {c.icon} {status}
    </span>
  );
}

